"""Phase 0d: write docs/source/geo_reference.md from BCGNIS results, ATES landmarks and datum/survey outputs.
Inputs: build/bcgnis.json, ates KMZ, build/datum_check.json, build/dem_survey.json.  Run: uv run make_geo_reference.py
"""
import json, pathlib, re, zipfile
import pyproj

ROOT = pathlib.Path(__file__).resolve().parent.parent
B = ROOT / "build"
t = pyproj.Transformer.from_crs(4617, 2955, always_xy=True)
bcg = json.loads((B / "bcgnis.json").read_text())
dc = json.loads((B / "datum_check.json").read_text())
ds = json.loads((B / "dem_survey.json").read_text())

s = zipfile.ZipFile(ROOT / "ates" / "Kokanee Glacier.kmz").read("doc.kml").decode()
ates = {}
for pm in re.findall(r"<Placemark>(.*?)</Placemark>", s, re.S):
    if "<Point" in pm and ("destination" in pm or "cabin_styles" in pm):
        n = re.search(r"<name>(.*?)</name>", pm).group(1)
        ates[n] = [round(float(v), 6) for v in re.search(r"<coordinates>(.*?)</coordinates>", pm, re.S).group(1).split(",")[:2]]

GUIDE_ELEV = {"Mount Giegerich": "2,249 m", "Mount John Carter": "2,606 / 2,610 m (lidar summit 2611 m)", "Cond Peak": "2,801 m (lidar 2805.6 m)",
              "Kokanee Peak": "2,790 m", "Grays Peak": "2,753 m", "Riddles Knob": "2,160 m"}

def row(name, ll, src):
    e, n = t.transform(*ll)
    return f"| {name} | {src} | {ll[0]:.6f}, {ll[1]:.6f} | {e:,.0f} / {n:,.0f} | {GUIDE_ELEV.get(name, '')} |"

lines = ["# Geo reference (computed once; agents use this, never the lidar or PDF)", "",
         "Generated by `tools/make_geo_reference.py`. All app data is WGS84 `[lon, lat]`. Analysis CRS: **EPSG:2955 NAD83(CSRS) / UTM 11N**.", "",
         "## Project bounding box", "",
         "- UTM 11N: E 480,500–494,500, N 5,494,500–5,519,000 (14 × 24.5 km). This covers the ATES extent plus a margin.",
         "- Lon/lat (approx): −117.268 to −117.074, 49.603 to 49.824.",
         "- Pilot area (Phase 1): E 484,500–490,500, N 5,509,500–5,514,500. It covers the cabin, Kaslo Lake, Riddles Knob, the lidar edge and the Keyhole (the glacier, which is part lidar and part MRDEM).", "",
         "## Cabin",
         f"- Kokanee Glacier Cabin (ATES): {ates['Cabin'][0]}, {ates['Cabin'][1]}. The heli-pad is just N/NW of the cabin. Enterprise Pass (BCGNIS) is ~240 m WNW and ~60 m above.", "",
         "## Named features (control points)",
         "",
         "Sources:",
         "- **BCGNIS**: BC Geographic Names, NAD83, accurate to about ±50–80 m.",
         "- **ATES**: landmarks in `ates/Kokanee Glacier.kmz`.",
         "- **lidar**: the highest lidar cell, used where a summit is covered.",
         "",
         "Use the lidar summit when one is given. Otherwise use the BCGNIS or ATES point, and snap to terrain with `terrain_probe.py`.", "",
         "| Name | Source | lon, lat | UTM E / N | Elevation (guide / lidar) |", "|---|---|---|---|---|"]
for n, v in sorted(bcg.items()):
    lines.append(row(n, v["lonlat"], f"BCGNIS ({v['type']})"))
for n, ll in sorted(ates.items()):
    lines.append(row(n, ll, "ATES"))
lines += ["",
          "Not in BCGNIS (unofficial names). Locate them from the guide text and terrain:",
          "- **Tanal Peak**: directly N of the cabin, on the E side of Tanal Lake.",
          "- **Riddles Knob**: 2160 m, on the rib between Commission and Outlook creeks, S of Kaslo Lake.",
          "- **Smuggler's Ridge**: NW crest from The Pyramids (488,200 / 5,511,300) to about 486,600 / 5,512,600. ATES has 'Smugglers Ridge'.",
          "- **Mount Kitchener**: ATES point.",
          "- **Happy Valley** and **Enterprise Ridge**: ATES points.",
          "- **Slocan Chief Cabin**: historic cabin, NE of Kaslo Lake, along the summer trail.",
          "- **Enchanted Forest**: trees W of Enterprise Pass.", "",
          "## Guide grid refs (S&I section)",
          "The refs are **NAD83 UTM 11N** (see `docs/decisions/horizontal-datum.md`); use them as printed. 'North summit of Outlook Mtn' is Mount John Carter. The Lemon Pass crest ref is unreliable.", "",
          "| Ref | Printed E / N | Nearest control | Distance (m) |", "|---|---|---|---|"]
for g in dc["guide"]:
    lines.append(f"| {g['ref']} | {g['printed'][0]} / {g['printed'][1]} | {g['control']} | {g['h83_m']} |")
lines += ["", "## Elevation data coverage (see docs/decisions/dem-source.md)", "",
          "| Source | Native resolution | Bbox coverage | Test sites (cabin, Tanal, glacier, west gap) |", "|---|---|---|---|"]
for n, v in ds.items():
    st = ", ".join(f"{x:.0%}" for x in v.get("sites", {}).values())
    lines.append(f"| {n} | {v['native_res_m']:g} m | {v['bbox_coverage']:.0%} | {st} |")
lines += ["", "- **Local lidar gaps:** a hole at about E 485,500–491,500 × N 5,511,500–5,516,500, and no coverage west of E ~485,500.",
          "- **Outside the lidar:** the cabin, Kaslo Lake, Tanal, Enterprise Pass, Robert Smith, Nansen, Giegerich and the N half of Kokanee Glacier are MRDEM-30 only.",
          "- **Inside the lidar:** John Carter, Outlook, the Pyramid, Esmeralda, Cond and Gray's are covered."]
out = ROOT / "docs" / "source" / "geo_reference.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", out, len(lines), "lines")
